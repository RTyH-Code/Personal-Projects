#!/usr/bin/env python3
"""Legendary pass: one-time post-game encounters for every legendary/event Pokemon.

* Mew, Celebi, Raikou, Entei and Suicune appear as overworld sprites after
  the first Hall of Fame entry.
* Pokemon without an overworld sprite (Regis, weather trio, Latis, Jirachi)
  are marked by a meteorite rock (the Birth Island stone) that shows a hint
  before you become Champion and starts the battle after.
* There is no roaming beast: Raikou, Entei and Suicune are static (the
  roamer itself is disabled in src/roamer.c and the One Island script).
* The first Hall of Fame entry also hands out the Mystic and Aurora Tickets,
  which open Navel Rock (Lugia, Ho-Oh) and Birth Island (Deoxys).
Losing or running keeps the encounter available; catching removes it.

Run once from the repo root on a checkout without these changes applied:
    python3 tools/hack/legendaries.py
"""
import json
import struct

# name, map dir, x, y, level, has overworld sprite.
# Marker objects (no sprite) are placed at MARKER_POS, faced from STAND_POS.
LEGENDS = [
    ("MEW",       "PokemonMansion_B1F",                     6,  4, 30, True),
    ("CELEBI",    "ViridianForest",                        36, 16, 30, True),
    ("RAIKOU",    "PowerPlant",                            40, 17, 50, True),
    ("ENTEI",     "MtEmber_Exterior",                      34, 21, 50, True),
    ("SUICUNE",   "TwoIsland_CapeBrink",                   12, 36, 50, True),
    ("REGIROCK",  "SevenIsland_TanobyRuins_LiptooChamber", 11,  7, 40, False),
    ("REGICE",    "SevenIsland_TanobyRuins_WeepthChamber", 10,  7, 40, False),
    ("REGISTEEL", "SevenIsland_TanobyRuins_DilfordChamber", 10, 7, 40, False),
    ("KYOGRE",    "SeafoamIslands_B3F",                    20, 13, 45, False),
    ("GROUDON",   "MtEmber_RubyPath_B3F",                  13,  3, 45, False),
    ("RAYQUAZA",  "SevenIsland_SevaultCanyon",             13,  3, 70, False),
    ("LATIAS",    "SixIsland_OutcastIsland",               10, 21, 40, False),
    ("LATIOS",    "FiveIsland_MemorialPillar",             12,  3, 40, False),
    ("JIRACHI",   "MtMoon_B2F",                            11,  2, 30, False),
]

MARKER_POS = {"REGIROCK": (11, 8), "REGICE": (10, 8), "REGISTEEL": (10, 8), "KYOGRE": (20, 14),
              "GROUDON": (13, 3), "RAYQUAZA": (13, 4), "LATIAS": (10, 22), "LATIOS": (12, 4),
              "JIRACHI": (11, 3)}
STAND_POS = {n: (x, y + 1) for n, (x, y) in MARKER_POS.items()}

# Free flags: the 9 unused hidden-item flags, then the trainer flags of
# Ruby/Sapphire placeholder trainers that FireRed never battles.
FREE_FLAGS = ["FLAG_UNUSED_0x4A%s" % c for c in "789ABCDEF"] + [
    "(TRAINER_FLAGS_START + TRAINER_%s)" % t for t in
    ("AQUA_LEADER", "AQUA_GRUNT_M", "AQUA_GRUNT_F", "RS_AROMA_LADY",
     "RS_RUIN_MANIAC", "INTERVIEWER", "RS_TUBER_F", "RS_TUBER_M")]
RELEASED_FLAG = "FLAG_HACK_LEGENDS_RELEASED"


def flag(name):
    return "FLAG_HACK_CAUGHT_" + name


def label(name):
    return "Hack_EventScript_Legend_" + name.title().replace("_", "")


def tile_elevation(mapdir, x, y):
    m = json.load(open(f"data/maps/{mapdir}/map.json"))
    layouts = {l["id"]: l for l in json.load(open("data/layouts/layouts.json"))["layouts"] if "id" in l}
    L = layouts[m["layout"]]
    raw = open(L["blockdata_filepath"], "rb").read()
    tile = struct.unpack_from("<H", raw, 2 * (y * L["width"] + x))[0]
    return tile >> 12


def write_flags():
    p = "include/constants/flags.h"
    s = open(p).read()
    lines = ["", "// FireRed QoL+Hard: legendary encounter flags (see tools/hack/legendaries.py)",
             f"#define {RELEASED_FLAG:<32} {FREE_FLAGS[0]}"]
    for (name, *_), f in zip(LEGENDS, FREE_FLAGS[1:]):
        lines.append(f"#define {flag(name):<32} {f}")
    anchor = "#define TRAINER_FLAGS_END"
    i = s.index("\n", s.index(anchor))
    s = s[:i + 1] + "\n".join(lines) + "\n" + s[i + 1:]
    open(p, "w").write(s)


def write_scripts():
    out = ["@ FireRed QoL+Hard: legendary encounters (generated by tools/hack/legendaries.py)", ""]
    out += ["EventScript_HackReleaseLegends::",
            "\tsetflag FLAG_ENABLE_SHIP_NAVEL_ROCK",
            "\tsetflag FLAG_ENABLE_SHIP_BIRTH_ISLAND",
            f"\tgoto_if_set {RELEASED_FLAG}, EventScript_Return",
            f"\tsetflag {RELEASED_FLAG}",
            "\tadditem ITEM_MYSTIC_TICKET",
            "\tadditem ITEM_AURORA_TICKET"]
    out += [f"\tclearflag {flag(n)}" for n, *_, sprite in LEGENDS if sprite]
    out += ["\treturn", ""]
    out += ["EventScript_HackHideLegends::"]
    out += [f"\tsetflag {flag(n)}" for n, *_, sprite in LEGENDS if sprite]
    out += ["\treturn", ""]
    for name, mapdir, x, y, level, sprite in LEGENDS:
        out += [f"{label(name)}::",
                "\tgoto_if_questlog EventScript_ReleaseEnd",
                "\tlock"]
        if sprite:
            out += ["\tfaceplayer"]
        else:
            out += [f"\tgoto_if_set {flag(name)}, EventScript_ReleaseEnd",
                    "\tgoto_if_unset FLAG_SYS_GAME_CLEAR, Hack_EventScript_LegendSleeping"]
        out += ["\tspecial QuestLog_CutRecording",
                f"\tsetwildbattle SPECIES_{name}, {level}",
                "\twaitse",
                f"\tplaymoncry SPECIES_{name}, CRY_MODE_ENCOUNTER",
                "\tmessage Text_Gyaoo",
                "\twaitmessage",
                "\twaitmoncry",
                "\tdelay 10",
                "\tplaybgm MUS_ENCOUNTER_GYM_LEADER, 0",
                "\twaitbuttonpress",
                "\tsetflag FLAG_SYS_SPECIAL_WILD_BATTLE",
                "\tspecial StartLegendaryBattle",
                "\twaitstate",
                "\tclearflag FLAG_SYS_SPECIAL_WILD_BATTLE",
                "\tspecialvar VAR_RESULT, GetBattleOutcome",
                "\tgoto_if_ne VAR_RESULT, B_OUTCOME_CAUGHT, EventScript_ReleaseEnd",
                f"\tsetflag {flag(name)}"]
        out += ["\tremoveobject VAR_LAST_TALKED"]
        out += ["\trelease", "\tend", ""]
    out += ["Hack_EventScript_LegendSleeping::",
            "\tmsgbox Hack_Text_LegendSleeping",
            "\trelease",
            "\tend",
            "",
            "Hack_Text_LegendSleeping::",
            '\t.string "A powerful presence is sleeping here.\\p'
            'Perhaps a true CHAMPION\\ncould wake it…$"',
            ""]
    open("data/scripts/hack_legendaries.inc", "w").write("\n".join(out))

    p = "data/event_scripts.s"
    s = open(p).read()
    anchor = '\t.include "data/scripts/test.inc"\n'
    s = s.replace(anchor, anchor + '\t.include "data/scripts/hack_legendaries.inc"\n', 1)
    # Hide the sprite legendaries on a new game...
    s = s.replace("EventScript_ResetAllMapFlags::\n",
                  "EventScript_ResetAllMapFlags::\n\tcall EventScript_HackHideLegends\n", 1)
    open(p, "w").write(s)
    # ...and release them (plus tickets) at the first Hall of Fame entry.
    p = "data/scripts/hall_of_fame.inc"
    s = open(p).read()
    s = s.replace("EventScript_ResetLegendaries::\n",
                  "EventScript_ResetLegendaries::\n\tcall EventScript_HackReleaseLegends\n", 1)
    open(p, "w").write(s)


def write_map_events():
    for name, mapdir, x, y, level, sprite in LEGENDS:
        p = f"data/maps/{mapdir}/map.json"
        m = json.load(open(p))
        if sprite:
            gfx, pos, height = f"OBJ_EVENT_GFX_{name}", (x, y), tile_elevation(mapdir, x, y)
        else:
            gfx, pos = "OBJ_EVENT_GFX_METEORITE", MARKER_POS[name]
            height = tile_elevation(mapdir, *STAND_POS[name])
        m.setdefault("object_events", []).append({
            "type": "object",
            "graphics_id": gfx,
            "x": pos[0], "y": pos[1],
            "elevation": height,
            "movement_type": "MOVEMENT_TYPE_FACE_DOWN",
            "movement_range_x": 1, "movement_range_y": 1,
            "trainer_type": "TRAINER_TYPE_NONE",
            "trainer_sight_or_berry_tree_id": "0",
            "script": label(name),
            "flag": flag(name),
        })
        with open(p, "w") as f:
            json.dump(m, f, indent=2)
            f.write("\n")


write_flags()
write_scripts()
write_map_events()
print(f"{len(LEGENDS)} legendary encounters added")
